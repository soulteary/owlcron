VERIFY_REDIS_TESTS
docker exec "$runner" go test -race ./cli -run '^TestRedisRealCLIBackupRestore$' \
    -count="$repeats" -timeout=360s -v | tee "$results/remote-cli.log"
docker exec "$runner" go test -race ./api ./engine \
    -run '^Test(SingleNodeSystemLifecycle|ClusterAuthenticatedDispatchAndReconnect|PrimaryOutageAutomaticTakeoverPreservesCursor)$/^Redis$' \
    -count="$repeats" -timeout=360s -v | tee "$results/remote-services.log"
python3 - "$results/remote-cli.log" "$results/remote-services.log" "$repeats" <<'VERIFY_REDIS_SERVICES'
