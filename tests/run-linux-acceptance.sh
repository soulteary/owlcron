#!/usr/bin/env bash
# Real Linux processes and isolated remote services; no Docker socket in runner.
set -euo pipefail
root=$(cd "$(dirname "$0")/.." && pwd)
command -v docker >/dev/null
command -v python3 >/dev/null
run_dir=$(mktemp -d "${TMPDIR:-/tmp}/owlcron-linux-acceptance.XXXXXXXX")
run_dir=$(cd "$run_dir" && pwd -P)
mkdir -p "$run_dir/control" "$run_dir/build/work" "$run_dir/build/cache" "$run_dir/modules" "$run_dir/s3-data"
build_dir=${OWLCRON_LINUX_BUILD_DIR:-"$run_dir/build"}
mkdir -p "$build_dir/work" "$build_dir/cache"
build_dir=$(cd "$build_dir" && pwd -P)
results=${OWLCRON_ACCEPTANCE_RESULTS:-"$run_dir/results"}
mkdir -p "$results"
results=$(cd "$results" && pwd -P)
name="owlcron-acceptance-$(date +%s)-$$"
network="$name-network"
s3="$name-s3"
couchbase="$name-couchbase"
runner="$name-runner"
controller_pid=
go_image=${OWLCRON_LINUX_GO_IMAGE:-golang:1.27.3-trixie}
s3_image=${OWLCRON_LINUX_S3_IMAGE:-owlcron-acceptance-minio:2025-04-22}
cb_image=${OWLCRON_LINUX_COUCHBASE_IMAGE:-couchbase/server:community-7.6.2}
repeats=${OWLCRON_ACCEPTANCE_COUNT:-1}
[[ "$repeats" =~ ^[1-3]$ ]] || { echo 'OWLCRON_ACCEPTANCE_COUNT must be 1, 2 or 3' >&2; exit 1; }
PYTHONDONTWRITEBYTECODE=1 python3 -m unittest discover -s "$root/tests" -p test_acceptance_control.py \
    2>&1 | tee "$results/controller-tests.log"

cleanup() {
    code=$?
    trap - EXIT INT TERM
    if [[ -n "$controller_pid" ]]; then kill "$controller_pid" 2>/dev/null || true; wait "$controller_pid" 2>/dev/null || true; fi
    for container in "$runner" "$s3" "$couchbase"; do
        # Names are generated by this invocation; never select by a broad label.
        docker unpause "$container" >/dev/null 2>&1 || true
        docker logs --tail 100 "$container" >"$results/$container.log" 2>&1 || true
        docker rm -f "$container" >/dev/null 2>&1 || true
    done
    docker network rm "$network" >/dev/null 2>&1 || true
    echo "Acceptance exit: $code; evidence: $results"
    # Retain the unique run directory for failed-run investigation; no global prune.
    exit "$code"
}
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

if [[ -n "${OWLCRON_LINUX_MODULE_CACHE:-}" ]]; then
    module_dir=$(cd "$OWLCRON_LINUX_MODULE_CACHE" && pwd -P)
else
    module_dir="$run_dir/modules"
fi
docker network create --label io.owlcron.acceptance=true "$network" >/dev/null
if [[ -n "${OWLCRON_LINUX_MINIO_BINARY:-}" ]]; then
    # The caller must supply a Linux binary for the Docker engine architecture.
    s3_image="$go_image"
    s3_arguments=(-v "$OWLCRON_LINUX_MINIO_BINARY:/usr/local/bin/minio:ro" --entrypoint /usr/local/bin/minio)
else
    s3_arguments=()
    if [[ -z "${OWLCRON_LINUX_S3_IMAGE:-}" ]]; then
        docker build -f "$root/tests/Dockerfile.minio-acceptance" -t "$s3_image" "$root/tests" >"$results/minio-build.log" 2>&1
    fi
fi
docker run -d --name "$s3" --label io.owlcron.acceptance=true --network "$network" \
    -v "$run_dir/s3-data:/data" \
    "${s3_arguments[@]}" -e MINIO_ROOT_USER=owlcron-test -e MINIO_ROOT_PASSWORD=owlcron-test-secret \
    "$s3_image" server /data --address :9000 >/dev/null
docker run -d --name "$couchbase" --label io.owlcron.acceptance=true --network "$network" "$cb_image" >/dev/null
ready=false
for ((i=0; i<60; i++)); do
    if docker exec "$couchbase" /opt/couchbase/bin/couchbase-cli cluster-init -c 127.0.0.1 \
        --cluster-username Administrator --cluster-password owlcron-test-secret \
        --services data --cluster-ramsize 512 >"$results/couchbase-init.log" 2>&1; then ready=true; break; fi
    sleep 2
done
[[ "$ready" == true ]] || { echo 'Isolated Couchbase initialization failed' >&2; exit 1; }
docker exec "$couchbase" /opt/couchbase/bin/couchbase-cli bucket-create -c 127.0.0.1 \
    -u Administrator -p owlcron-test-secret --bucket owlcron-integration \
    --bucket-type couchbase --bucket-ramsize 256 --bucket-replica 0 --wait >"$results/couchbase-bucket.log" 2>&1
python3 "$root/tests/acceptance_control.py" --directory "$run_dir/control" \
    --container "$s3" --container "$couchbase" >"$results/controller.log" 2>&1 &
controller_pid=$!
docker run -d --name "$runner" --label io.owlcron.acceptance=true --network "$network" \
    -v "$root:/workspace:ro" -v "$module_dir:/go/pkg/mod" \
    -v "$run_dir/control:/control" -v "$build_dir:/build" -w /workspace \
    -e GOCACHE=/build/cache -e GOTMPDIR=/build/work -e GOFLAGS=-p=2 \
    -e "GOPROXY=${GOPROXY:-https://proxy.golang.org,direct}" \
    -e OWLCRON_TEST_CONTROL_DIR=/control \
    -e "OWLCRON_TEST_S3_ENDPOINT=http://$s3:9000" \
    -e "OWLCRON_TEST_COUCHBASE_CONNECTION=couchbase://$couchbase" \
    -e "OWLCRON_TEST_S3_CONTAINER=$s3" -e "OWLCRON_TEST_COUCHBASE_CONTAINER=$couchbase" \
    "$go_image" sleep infinity >/dev/null
{
    docker exec "$runner" sh -c 'test "$(uname -s)" = Linux && uname -srmo && go version'
    docker exec "$s3" /usr/local/bin/minio --version
    docker exec "$s3" sha256sum /usr/local/bin/minio
    for image in "$go_image" "$s3_image" "$cb_image"; do docker image inspect "$image" --format '{{.Id}} {{.Architecture}}'; done
} | tee "$results/environment.log"
# Baseline has external-service opt-ins cleared: faults below run serially.
docker exec -e OWLCRON_TEST_S3_ENDPOINT= -e OWLCRON_TEST_COUCHBASE_CONNECTION= \
    -e OWLCRON_TEST_S3_CONTAINER= -e OWLCRON_TEST_COUCHBASE_CONTAINER= "$runner" \
    go test -race ./... -count=1 -timeout=300s | tee "$results/linux-race.log"
docker exec "$runner" go test -race ./storage \
    -run '^Test(S3RealStorage|S3RealTransportFaultRecovery|S3RealCommittedResponseLossRecovery|S3RealServerRestartRecovery|CouchbaseRealStorage|CouchbaseRemoteFaultRecovery)$' \
    -count="$repeats" -timeout=1200s -v | tee "$results/remote-storage.log"
docker exec -e OWLCRON_REMOTE_PROCESS_BACKENDS=S3,Couchbase \
    -e "OWLCRON_REMOTE_S3_CONFIG={\"endpoint\":\"http://$s3:9000\",\"bucket\":\"owlcron-integration\",\"access_key\":\"owlcron-test\",\"secret_key\":\"owlcron-test-secret\"}" \
    -e "OWLCRON_REMOTE_COUCHBASE_CONFIG={\"connection_string\":\"couchbase://$couchbase\",\"bucket\":\"owlcron-integration\",\"username\":\"Administrator\",\"password\":\"owlcron-test-secret\"}" \
    "$runner" go test -race . -run '^TestProcessRemoteClusterRecovery$' -count="$repeats" -timeout=1500s -v \
    | tee "$results/remote-process.log"
docker exec "$runner" go vet ./... | tee "$results/vet.log"
